#include <iostream>
using namespace std;

int main() {

    for (char c = 'A'; c <= 'Z'; c++) {
        cout << c;
    }
    cout << endl;

    for (char c = 'a'; c <= 'z'; c++) {
        cout << c;
    }
    cout << endl;

    for (char c = '0'; c <= '9'; c++) {
        cout << c;
    }
    cout << endl;

    return 0;
}